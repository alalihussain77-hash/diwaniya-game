// All proverbs combined
export const proverbsList: string[] = [
  ...proverbsQuestions[200],
  ...proverbsQuestions[400],
  ...proverbsQuestions[600]
];

// Helper to generate a Question object
const createProverbQuestion = (item: string, pts: number, idSuffix: string): Question => {
  const pool = proverbsQuestions[pts] || proverbsList;
  const otherOptions = pool
    .filter((w) => w !== item)
    .sort(() => (idSuffix.length % 3) - 1)
    .slice(0, 3);

  const options = [item, ...otherOptions].sort(() => (item.length % 2 === 0 ? 1 : -1));

  return {
    id: `wk_prv_${pts}_${idSuffix}`,
    points: pts,
    category: 'ولا كلمة أمثال',
    question: 'امسح الباركود للحصول على السؤال',
    options: options,
    correctAnswer: item, // النص الصريح المباشر Plain Text
    explanation: `المثل المطلوب تمثيله: ${item}`,
    hint: `مثل شعبي (${item})`
  };
};

// Generate full 100 questions for the 100-bank:
// 34 questions at 200 pts, 33 questions at 400 pts, 33 questions at 600 pts
export const walaKelmaProverbsQuestions: Question[] = Array.from({ length: 100 }, (_, index) => {
  const qNum = index + 1;
  let pts = 200;
  let pool = proverbsQuestions[200];
  if (qNum > 34 && qNum <= 67) {
    pts = 400;
    pool = proverbsQuestions[400];
  } else if (qNum > 67) {
    pts = 600;
    pool = proverbsQuestions[600];
  }

  const selectedItem = pool[(qNum - 1) % pool.length];
  return createProverbQuestion(selectedItem, pts, String(qNum).padStart(3, '0'));
});
