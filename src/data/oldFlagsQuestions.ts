export function toWikimediaDirectPng(rawUrl?: string, width = 512): string {
  if (!rawUrl) return '';
  let clean = rawUrl.trim();

  // If already proxied, return clean
  if (clean.startsWith('https://wsrv.nl/?url=') || clean.startsWith('http://wsrv.nl/?url=')) {
    return clean;
  }

  // Strip any previous weserv prefix to normalize
  if (clean.startsWith('https://images.weserv.nl/?url=')) {
    clean = decodeURIComponent(clean.replace('https://images.weserv.nl/?url=', ''));
  }

  const cleanWithoutProto = clean.replace(/^https?:\/\//, '');
  return `https://wsrv.nl/?url=${cleanWithoutProto}`;
}

